@Suppress("LongParameterList")
private fun sc(
    name: String,
    agility: Int,
    xp: Double,
    style: ShortcutStyle,
    ax: Int,
    az: Int,
    bx: Int,
    bz: Int,
    vararg locs: String,
    level: Int = 0,
    oneWay: Boolean = false,
    otherRequirement: Pair<String, Int>? = null,
): Shortcut =
    Shortcut(
        name = name,
        locs = locs.toList(),
        level = agility,
        xp = xp,
        sideA = CoordGrid(ax, az, level),
        sideB = CoordGrid(bx, bz, level),
        style = style,
        oneWay = oneWay,
        otherRequirement = otherRequirement,
    )
